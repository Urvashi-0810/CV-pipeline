"""DEVELOPMENT ONLY: a "Test (no AI)" provider.

Enabled only when LLM_ALLOW_TEST_PROVIDER=true. It does not understand anything; it
returns a canned letter built from the first table it finds in the attachments, so the
chat → letter → preview → download flow can be tried without an API key.
"""

import json
import re

from app.modules.llm.base import Adapter, LlmRequest, LlmResult

TABLE_LINE = re.compile(r"^\|(.+)\|$")


class TestAdapter(Adapter):
    provider = "test"

    def __init__(self, model: str = "test") -> None:
        self.model = model

    async def generate(self, request: LlmRequest) -> LlmResult:
        texts = [p.text or "" for t in request.turns if t.role == "user" for p in t.parts if p.kind == "text"]
        joined = "\n".join(texts)
        last_user = texts[-1] if texts else ""
        image_ids = re.findall(r"image_id=(img-\d+)", joined)

        if "Attachment" not in joined:
            body = {
                "action": "ask", "message": "Please attach the demand inquiry (and the JD if you have one).",
                "questions": ["Attach the demand inquiry mail (.docx)."], "missing_fields": [],
                "letter": None, "extracted": None,
            }
        elif re.search(r"\b(weather|joke|cricket)\b", last_user, re.I):
            body = {"action": "refuse", "message": "", "questions": [], "missing_fields": [],
                    "letter": None, "extracted": None}
        elif last_user.strip().endswith("?"):
            body = {"action": "answer", "message": "(Test provider) I can only answer with a real AI provider.",
                    "questions": [], "missing_fields": [], "letter": None, "extracted": None}
        else:
            rows = [[c.strip() for c in m.group(1).split("|")]
                    for line in joined.splitlines() if (m := TABLE_LINE.match(line.strip()))]
            width = max((len(r) for r in rows), default=0)
            rows = [r + [""] * (width - len(r)) for r in rows if len(r) > 1][:15]
            blocks = [
                {"type": "paragraph", "text": "(Generated by the TEST provider — not real AI output.)"},
                {"type": "paragraph", "text": "**Employer:** [[MISSING: Employer]]"},
            ]
            if rows:
                blocks.append({"type": "heading", "text": "Positions", "level": 2})
                blocks.append({"type": "table", "columns": rows[0], "rows": rows[1:]})
            if image_ids:
                blocks.append({"type": "image", "image_id": image_ids[0], "caption": "Image from the JD"})
            body = {
                "action": "letter", "message": "Here is a test letter built from your attachments.",
                "questions": [], "missing_fields": ["Employer"],
                "letter": {"title": "Demand Letter (test)", "blocks": [
                    {"text": None, "level": None, "items": None, "columns": None, "rows": None,
                     "image_id": None, "caption": None, **b} for b in blocks]},
                "extracted": {"country": None, "employer": None, "vacancy": None, "trades": []},
            }
        return LlmResult(text=json.dumps(body), input_tokens=len(joined) // 4, output_tokens=200)
